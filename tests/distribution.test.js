import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';

const html = await readFile(new URL('../index.html', import.meta.url), 'utf8');

test('GitHub Pages root ships styles and the complete app without external assets', () => {
  assert.ok(html.includes('<!-- Generated by npm run build from src/. -->'));
  assert.match(html, /<style>[\s\S]+<\/style>/);
  assert.match(html, /<script id="nami-app">[\s\S]+<\/script>/);
  assert.doesNotMatch(html, /<script\b[^>]*\bsrc=/i);
  assert.doesNotMatch(html, /<link\b[^>]*\brel="stylesheet"/i);
  assert.match(html, /href="data:image\/svg\+xml;base64,/);
  assert.match(html, /<meta name="nami-build" content="[0-9a-f]{12}"/);
});

test('the app parses as a classic script with no browser module resolution', () => {
  const code = html.match(/<script id="nami-app">([\s\S]*?)<\/script>/)[1];
  assert.doesNotThrow(() => new vm.Script(code));
});

test('the standalone page has immediate controls and a useful disabled-JavaScript state', () => {
  assert.doesNotMatch(html, /id="(?:welcome|enter)"/);
  assert.match(html, /<div id="controls" class="controls">/);
  assert.match(html, /<noscript>[\s\S]*JavaScriptを有効に/);
  assert.match(html, /id="loading"/);
});
