import { build, transform } from 'esbuild';
import { readFile, writeFile, mkdir, rename, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { createHash } from 'node:crypto';

const root = fileURLToPath(new URL('../', import.meta.url));
const target = ['safari15.4', 'chrome100', 'firefox100'];

// Ship one standalone HTML document. GitHub Pages serves main's root directly;
// neither a bundler at runtime nor any files outside /HealingBeach/ are needed.
const [bundle, stylesheet, template, icon] = await Promise.all([
  build({
    absWorkingDir: root,
    entryPoints: ['src/main.js'],
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target,
    minify: true,
    legalComments: 'inline',
    write: false,
  }),
  readFile(resolve(root, 'src/style.css'), 'utf8').then(css => transform(css, { loader: 'css', target, minify: true })),
  readFile(resolve(root, 'src/index.html'), 'utf8'),
  readFile(resolve(root, 'public/favicon.svg')),
]);

// Shader template literals retain indentation through minification. Strip
// insignificant line-end whitespace so the generated file passes Git checks.
const javascript = bundle.outputFiles[0].text.replace(/[\t ]+$/gm, '');
const buildId = createHash('sha256').update(template).update(stylesheet.code).update(javascript).update(icon).digest('hex').slice(0, 12);
const replacements = [
  ['<link rel="stylesheet" href="./style.css" />', `<style>${stylesheet.code.replace(/<\/style/gi, '<\\/style')}</style>`],
  ['<script type="module" src="./main.js"></script>', `<script id="nami-app">${javascript.replace(/<\/script/gi, '<\\/script')}</script>`],
  ['href="./favicon.svg"', `href="data:image/svg+xml;base64,${icon.toString('base64')}"`],
  ['</head>', `    <meta name="nami-build" content="${buildId}" />\n  </head>`],
];
let html = template;
for (const [placeholder, value] of replacements) {
  if (!html.includes(placeholder)) throw new Error(`Missing build placeholder: ${placeholder}`);
  html = html.replace(placeholder, () => value);
}
html = `<!-- Generated by npm run build from src/. -->\n${html}`;
await rm(resolve(root, 'dist'), { recursive: true, force: true });
await mkdir(resolve(root, 'dist'), { recursive: true });
for (const path of ['index.html', 'dist/index.html']) {
  const destination = resolve(root, path);
  await writeFile(`${destination}.tmp`, html);
  await rename(`${destination}.tmp`, destination);
}
console.log(`Built standalone beach: ${Math.round(Buffer.byteLength(html) / 1024)} KiB, build ${buildId}`);
